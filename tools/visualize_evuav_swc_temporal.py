def relative_or_absolute(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path.resolve())


def read_config(path: Path) -> tuple[SimpleNamespace, Mapping[str, Any]]:
    with path.open("r", encoding="utf-8") as handle:
        raw = yaml.safe_load(handle)
    if not isinstance(raw, Mapping):
        raise ValueError(f"Config must be a mapping: {path}")

    flattened: Dict[str, Any] = {"config": str(path)}
    for section_name, section in raw.items():
        if not isinstance(section, Mapping):
            raise ValueError(
                f"Config section {section_name!r} must be a mapping: {path}"
            )
        for key, value in section.items():
            flattened[str(key)] = value
    return SimpleNamespace(**flattened), raw


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def json_value(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if torch.is_tensor(value):
        return value.detach().cpu().tolist()
    raise TypeError(f"Cannot serialize {type(value).__name__}")


def prepare_output_dir(output_dir: Path, overwrite: bool) -> None:
    managed_files = OUTPUT_FILES + STALE_OUTPUT_FILES
    existing = [
        output_dir / name
        for name in managed_files
        if (output_dir / name).exists()
    ]
    if existing and not overwrite:
        formatted = "\n  ".join(str(path) for path in existing)
        raise FileExistsError(
            "Output files already exist. Pass --overwrite to replace them:\n  "
            + formatted
        )
    output_dir.mkdir(parents=True, exist_ok=True)
    if overwrite:
        for path in existing:
            path.unlink()


