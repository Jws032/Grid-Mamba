"""Visualize temporal SWC context features on EVUAV or EV-Flying.

The main paper figure produced by this tool contains two aligned rows:

1. raw EVUAV events with point-level target ground truth highlighted;
2. GT-free relative saliency derived only from the continuously updated SWC
   context tensor.

The first row accumulates the target trajectory from left to right, using
different colors for past and newly appended target events.  The model still
runs through the complete sample.  Only the requested windows are retained for
plotting, so their SWC states include all preceding windows.  Ground truth is
never used to normalize, aggregate, enhance, or color-scale the context map.
"""

