def load_sample(path: Path) -> tuple[np.ndarray, np.ndarray]:
    with np.load(path) as payload:
        required = {"ev_loc", "evs_norm"}
        missing = required.difference(payload.files)
        if missing:
            raise KeyError(f"Missing arrays in {path}: {sorted(missing)}")
        points = np.asarray(payload["ev_loc"][:, :3], dtype=np.float32)
        labels = np.asarray(payload["evs_norm"][:, 4], dtype=np.float32)

    if points.ndim != 2 or points.shape[1] != 3:
        raise ValueError(f"Expected ev_loc[:, :3] with shape [N, 3], got {points.shape}")
    if labels.ndim != 1 or labels.shape[0] != points.shape[0]:
        raise ValueError(
            f"Expected one label per point, got points={points.shape}, labels={labels.shape}"
        )
    if points.shape[0] == 0:
        raise ValueError(f"Sample contains no events: {path}")
    if not np.isfinite(points).all() or not np.isfinite(labels).all():
        raise ValueError(f"Sample contains non-finite values: {path}")
    return points, labels


def validate_model_config(model: torch.nn.Module, cfg: SimpleNamespace) -> None:
    if not bool(getattr(model, "use_spatial_window_context", False)):
        raise ValueError("The selected config has use_spatial_window_context=False")
    if model.spatial_window_context is None:
        raise ValueError("The selected model has no SpatialWindowContext module")

    window_size = float(getattr(cfg, "window_size"))
    stride = float(getattr(cfg, "spatial_context_stride"))
    if window_size <= 0.0:
        raise ValueError(f"window_size must be positive, got {window_size}")
    if stride <= 0.0:
        raise ValueError(f"spatial_context_stride must be positive, got {stride}")

    sensor_size = tuple(int(value) for value in getattr(cfg, "sensor_size"))
    if len(sensor_size) != 2 or min(sensor_size) <= 0:
        raise ValueError(f"sensor_size must contain positive [height, width], got {sensor_size}")

    swc = model.spatial_window_context
    expected_shape = (
        int(math.ceil(sensor_size[0] / stride)),
        int(math.ceil(sensor_size[1] / stride)),
    )
    actual_shape = (swc.spatial_token_h, swc.spatial_token_w)
    if actual_shape != expected_shape:
        raise ValueError(
            f"Expected a {expected_shape[0]}x{expected_shape[1]} SWC map, got "
            f"{actual_shape[0]}x{actual_shape[1]}"
        )


def make_window_layout(
    points: torch.Tensor,
    labels: torch.Tensor,
    window_size: float,
) -> Dict[str, torch.Tensor]:
    sort_idx = torch.argsort(points[:, 2])
    points_sorted = points[sort_idx]
    labels_sorted = labels[sort_idx]
    window_ids = torch.div(
        points_sorted[:, 2] - points_sorted[0, 2],
        window_size,
        rounding_mode="floor",
    ).long()
    _, counts = torch.unique_consecutive(window_ids, return_counts=True)
    offsets = torch.zeros(counts.numel() + 1, dtype=torch.long, device=points.device)
    torch.cumsum(counts, dim=0, out=offsets[1:])
    return {
        "sort_idx": sort_idx,
        "points": points_sorted,
        "labels": labels_sorted,
        "window_ids": window_ids,
        "counts": counts,
        "offsets": offsets,
    }


def capture_swc_windows(
    model: torch.nn.Module,
    points: torch.Tensor,
    start_window: int,
    num_windows: int,
) -> tuple[torch.Tensor, List[Dict[str, torch.Tensor]]]:
    swc = model.spatial_window_context
    original_step = swc.step
    stop_window = start_window + num_windows
    captures: List[Dict[str, torch.Tensor]] = []
    window_counter = 0

    def traced_step(
        window_points: torch.Tensor,
        fused_feat: torch.Tensor,
        state=None,
        cell_idx: torch.Tensor | None = None,
    ):
        nonlocal window_counter
        current_window = window_counter
        window_counter += 1

        if cell_idx is None:
            cell_idx = swc._get_spatial_cell_indices(window_points)

        should_capture = start_window <= current_window < stop_window
        pre_prob = None
        if should_capture:
            pre_prob = torch.sigmoid(model._classify_features(fused_feat).float())

        enhanced_feat, new_state = original_step(
            window_points,
            fused_feat,
            state,
            cell_idx=cell_idx,
        )

        if should_capture:
            post_prob = torch.sigmoid(model._classify_features(enhanced_feat).float())
            captures.append(
                {
                    "window_index": torch.tensor(current_window, dtype=torch.int64),
                    "points": window_points.detach().float().cpu(),
                    "cell_idx": cell_idx.detach().long().cpu(),
                    "pre_prob": pre_prob.detach().float().cpu(),
                    "post_prob": post_prob.detach().float().cpu(),
                    "raw_token_map": new_state["prev_raw_token_map"]
                    .detach()
                    .float()
                    .cpu(),
                    "effective_token_map": new_state["prev_token_map"]
                    .detach()
                    .float()
                    .cpu(),
                    "context_map": new_state["prev_context_map"]
                    .detach()
                    .float()
                    .cpu(),
                }
            )
        return enhanced_feat, new_state

    swc.step = traced_step
    try:
        traced_logits, _ = model(points)
    finally:
        swc.step = original_step

    if traced_logits is None:
        raise RuntimeError("Model returned no logits")
    if len(captures) != num_windows:
        raise RuntimeError(
            f"Expected {num_windows} captured windows, got {len(captures)}; "
            f"the sample contains {window_counter} model windows"
        )
    return traced_logits, captures


def auc_binary(labels: np.ndarray, scores: np.ndarray) -> float:
    labels = np.asarray(labels, dtype=np.int64)
    scores = np.asarray(scores, dtype=np.float64)
    positive = labels == 1
    negative = labels == 0
    num_positive = int(positive.sum())
    num_negative = int(negative.sum())
    if num_positive == 0 or num_negative == 0:
        return float("nan")

    order = np.argsort(scores, kind="mergesort")
    sorted_scores = scores[order]
    ranks = np.empty(scores.size, dtype=np.float64)
    start = 0
    while start < scores.size:
        end = start + 1
        while end < scores.size and sorted_scores[end] == sorted_scores[start]:
            end += 1
        ranks[order[start:end]] = 0.5 * (start + 1 + end)
        start = end
    rank_sum = float(ranks[positive].sum())
    return (
        rank_sum - num_positive * (num_positive + 1) / 2.0
    ) / (num_positive * num_negative)


def safe_ratio(numerator: float, denominator: float) -> float:
    return float(numerator / denominator) if denominator > 0 else 0.0


def aggregate_cell_values(
    capture: Mapping[str, torch.Tensor],
    labels: torch.Tensor,
    token_h: int,
    token_w: int,
    threshold: float,
) -> tuple[Dict[str, np.ndarray], Dict[str, Any], Dict[str, np.ndarray]]:
    num_cells = token_h * token_w
    cell_idx = capture["cell_idx"].numpy().astype(np.int64, copy=False)
    labels_np = labels.detach().float().cpu().numpy()
    pre_prob = capture["pre_prob"].numpy()
    post_prob = capture["post_prob"].numpy()
    delta_prob = post_prob - pre_prob

    if labels_np.shape[0] != cell_idx.shape[0]:
        raise ValueError(
            f"Label/capture length mismatch: labels={labels_np.shape[0]}, "
            f"captured={cell_idx.shape[0]}"
        )

    event_count = np.bincount(cell_idx, minlength=num_cells).astype(np.int64)
    target_count = np.bincount(
        cell_idx,
        weights=labels_np,
        minlength=num_cells,
    ).astype(np.float64)
    post_sum = np.bincount(cell_idx, weights=post_prob, minlength=num_cells)
    delta_sum = np.bincount(cell_idx, weights=delta_prob, minlength=num_cells)
    occupied = event_count > 0

    gt_ratio = np.divide(
        target_count,
        event_count,
        out=np.zeros(num_cells, dtype=np.float64),
        where=occupied,
    )
    post_map = np.divide(
        post_sum,
        event_count,
        out=np.zeros(num_cells, dtype=np.float64),
        where=occupied,
    )
    delta_map = np.divide(
        delta_sum,
        event_count,
        out=np.zeros(num_cells, dtype=np.float64),
        where=occupied,
    )

    context_map = capture["context_map"].numpy()
    context_l2 = np.linalg.norm(context_map, axis=-1).reshape(-1)
    raw_token_map = capture["raw_token_map"].numpy()
    raw_token_l2 = np.linalg.norm(raw_token_map, axis=-1).reshape(-1)

    target_cells = (target_count > 0) & occupied
    background_cells = (~target_cells) & occupied
    predicted = post_prob >= threshold
    truth = labels_np >= 0.5
    tp = int(np.logical_and(predicted, truth).sum())
    fp = int(np.logical_and(predicted, ~truth).sum())
    fn = int(np.logical_and(~predicted, truth).sum())
    tn = int(np.logical_and(~predicted, ~truth).sum())

    points_np = capture["points"].numpy()
    target_points = points_np[truth, :2]
    if target_points.size == 0:
        centroid = np.array([np.nan, np.nan], dtype=np.float64)
    else:
        centroid = np.median(target_points, axis=0).astype(np.float64)

    occupied_target_labels = target_cells[occupied].astype(np.int64)
    metrics = {
        "num_events": int(labels_np.size),
        "num_target_events": int(truth.sum()),
        "num_occupied_cells": int(occupied.sum()),
        "num_target_cells": int(target_cells.sum()),
        "centroid_x": float(centroid[0]),
        "centroid_y": float(centroid[1]),
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
        "iou": safe_ratio(tp, tp + fp + fn),
        "pd": safe_ratio(tp, tp + fn),
        "fa": safe_ratio(fp, fp + tn),
        "precision": safe_ratio(tp, tp + fp),
        "mean_delta_target_cells": float(delta_map[target_cells].mean()),
        "mean_delta_background_cells": float(delta_map[background_cells].mean()),
        "mean_context_target_cells": float(context_l2[target_cells].mean()),
        "mean_context_background_cells": float(context_l2[background_cells].mean()),
        "auc_delta_prob": auc_binary(
            occupied_target_labels,
            delta_map[occupied],
        ),
        "auc_context_l2": auc_binary(
            occupied_target_labels,
            context_l2[occupied],
        ),
        "auc_post_prob": auc_binary(
            occupied_target_labels,
            post_map[occupied],
        ),
        "auc_raw_token_l2": auc_binary(
            occupied_target_labels,
            raw_token_l2[occupied],
        ),
    }
    maps = {
        "gt_ratio": gt_ratio.reshape(token_h, token_w).astype(np.float32),
        "delta_prob": delta_map.reshape(token_h, token_w).astype(np.float32),
        "post_prob": post_map.reshape(token_h, token_w).astype(np.float32),
        "context_l2": context_l2.reshape(token_h, token_w).astype(np.float32),
        "raw_token_l2": raw_token_l2.reshape(token_h, token_w).astype(np.float32),
        "occupied_mask": occupied.reshape(token_h, token_w),
        "event_count": event_count.reshape(token_h, token_w),
        "target_count": target_count.reshape(token_h, token_w).astype(np.float32),
    }
    point_values = {
        "points": points_np.astype(np.float32, copy=False),
        "labels": labels_np.astype(np.float32, copy=False),
        "cell_idx": cell_idx,
        "pre_prob": pre_prob.astype(np.float32, copy=False),
        "post_prob": post_prob.astype(np.float32, copy=False),
        "delta_prob": delta_prob.astype(np.float32, copy=False),
    }
    return maps, metrics, point_values


def robust_symmetric_limit(values: np.ndarray, quantile: float = 0.99) -> float:
    finite = np.abs(values[np.isfinite(values)])
    if finite.size == 0:
        return 1.0
    limit = float(np.quantile(finite, quantile))
    if limit <= 0.0:
        limit = float(finite.max(initial=0.0))
    return max(limit, 1e-6)


def shared_percentile_limits(
    values: np.ndarray,
    low: float = 0.02,
    high: float = 0.98,
) -> tuple[float, float]:
    finite = values[np.isfinite(values)]
    if finite.size == 0:
        return 0.0, 1.0
    vmin = float(np.quantile(finite, low))
    vmax = float(np.quantile(finite, high))
    if math.isclose(vmin, vmax):
        vmax = vmin + 1e-6
    return vmin, vmax


def spatial_binomial_smooth(values: np.ndarray) -> np.ndarray:
    """Apply a reflection-padded 3x3 binomial filter independently per window."""
    if values.ndim != 3:
        raise ValueError(f"Expected [T, H, W] values, got {values.shape}")
    kernel = np.asarray(
        [[1.0, 2.0, 1.0], [2.0, 4.0, 2.0], [1.0, 2.0, 1.0]],
        dtype=np.float64,
    )
    kernel /= kernel.sum()
    padded = np.pad(values, ((0, 0), (1, 1), (1, 1)), mode="reflect")
    windows = np.lib.stride_tricks.sliding_window_view(
        padded,
        (CONTEXT_SMOOTH_KERNEL_SIZE, CONTEXT_SMOOTH_KERNEL_SIZE),
        axis=(1, 2),
    )
    return np.einsum("thwij,ij->thw", windows, kernel, optimize=True)


def spatial_median_filter(values: np.ndarray, kernel_size: int) -> np.ndarray:
    """Apply a reflection-padded spatial median independently per window."""
    if values.ndim != 3:
        raise ValueError(f"Expected [T, H, W] values, got {values.shape}")
    if kernel_size <= 0 or kernel_size % 2 == 0:
        raise ValueError(f"Median kernel must be a positive odd integer, got {kernel_size}")
    radius = kernel_size // 2
    padded = np.pad(
        values,
        ((0, 0), (radius, radius), (radius, radius)),
        mode="reflect",
    )
    windows = np.lib.stride_tricks.sliding_window_view(
        padded,
        (kernel_size, kernel_size),
        axis=(1, 2),
    )
    return np.median(windows, axis=(-2, -1))


def compute_gt_free_context_saliency(
    context_features: np.ndarray,
) -> Dict[str, np.ndarray]:
    """Derive context saliency using only the selected SWC context tensors.

    Channels are robustly standardized over all selected windows and spatial
    cells.  Their root-mean-square energy is lightly smoothed, then a 7x7 local
    median is subtracted to expose responses that stand above their local
    context background.  No labels, occupancy mask, point probabilities, or
    target locations enter this computation.
    """
    context = np.asarray(context_features, dtype=np.float64)
    if context.ndim != 4:
        raise ValueError(
            f"Expected context features with shape [T, H, W, C], got {context.shape}"
        )
    if not np.isfinite(context).all():
        raise ValueError("Context features contain non-finite values")

    reduce_axes = (0, 1, 2)
    channel_center = np.median(context, axis=reduce_axes)
    absolute_deviation = np.abs(context - channel_center[None, None, None, :])
    mad_scale = ROBUST_MAD_NORMALIZATION * np.median(
        absolute_deviation,
        axis=reduce_axes,
    )

    # The IQR and standard-deviation fallbacks make the tool safe for sparse
    # channels whose median absolute deviation is exactly zero.  Constant
    # channels are marked inactive and contribute zero standardized energy.
    quartiles = np.quantile(context, (0.25, 0.75), axis=reduce_axes)
    iqr_scale = (quartiles[1] - quartiles[0]) / 1.349
    std_scale = np.std(context, axis=reduce_axes)
    channel_scale = mad_scale.copy()
    scale_source = np.zeros(channel_scale.shape, dtype=np.uint8)

    use_iqr = (channel_scale < ROBUST_SCALE_EPSILON) & (
        iqr_scale >= ROBUST_SCALE_EPSILON
    )
    channel_scale[use_iqr] = iqr_scale[use_iqr]
    scale_source[use_iqr] = 1

    use_std = (channel_scale < ROBUST_SCALE_EPSILON) & (
        std_scale >= ROBUST_SCALE_EPSILON
    )
    channel_scale[use_std] = std_scale[use_std]
    scale_source[use_std] = 2

    inactive = channel_scale < ROBUST_SCALE_EPSILON
    channel_scale[inactive] = 1.0
    scale_source[inactive] = 3

    standardized = (
        context - channel_center[None, None, None, :]
    ) / channel_scale[None, None, None, :]
    if inactive.any():
        standardized[..., inactive] = 0.0

    standardized_energy = np.sqrt(np.mean(np.square(standardized), axis=-1))
    smoothed_energy = spatial_binomial_smooth(standardized_energy)
    local_baseline = spatial_median_filter(
        smoothed_energy,
        CONTEXT_LOCAL_MEDIAN_KERNEL_SIZE,
    )
    saliency = smoothed_energy - local_baseline

    outputs = {
        "context_standardized_energy": standardized_energy.astype(np.float32),
        "context_smoothed_energy": smoothed_energy.astype(np.float32),
        "context_local_median": local_baseline.astype(np.float32),
        "context_saliency": saliency.astype(np.float32),
        "context_channel_center": channel_center.astype(np.float32),
        "context_channel_scale": channel_scale.astype(np.float32),
        "context_channel_scale_source": scale_source,
    }
    for key, value in outputs.items():
        if not np.isfinite(value).all():
            raise AssertionError(f"Derived array {key} contains non-finite values")
    return outputs


